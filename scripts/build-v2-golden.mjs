import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileCurriculum } from '../src/curriculum-v2/compiler/compileCurriculum.js';
import { generateCoverage } from '../src/curriculum-v2/coverage/generateCoverage.js';
import { validateCurriculumSource } from '../src/curriculum-v2/validation/validateCurriculumSource.js';
import { validateRuntimeCurriculum } from '../src/curriculum-v2/validation/validateRuntimeCurriculum.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exampleDir = path.join(root, 'XcelerateAI Curriculum System', 'v2', 'examples', 'golden-curriculum');
const source = JSON.parse(fs.readFileSync(path.join(exampleDir, 'curriculum-source.json'), 'utf8'));
const sourceReport = validateCurriculumSource(source);
if (sourceReport.status !== 'PASS') throw new Error(JSON.stringify(sourceReport, null, 2));
const runtime = compileCurriculum(source);
const runtimeReport = validateRuntimeCurriculum(runtime);
if (runtimeReport.status !== 'PASS') throw new Error(JSON.stringify(runtimeReport, null, 2));

const validationReport = {
  status: 'PASS',
  curriculumId: source.curriculumId,
  revision: source.revision,
  blockingFailures: 0,
  warningCount: 0,
  noteCount: 1,
  passes: [
    { validator: 'V001-V014', name: 'Deterministic source validation', status: 'PASS', findings: [] },
    { validator: 'V018', name: 'Runtime contract validation', status: 'PASS', findings: [] }
  ],
  findings: [{
    code: 'GOLDEN-N001',
    severity: 'NOTE',
    message: 'Golden Curriculum URLs are structural example.com placeholders and are not verified learning resources.',
    affectedIds: source.resources.map((resource) => resource.id)
  }],
  semanticValidation: {
    status: 'NOT_APPLICABLE_TO_STRUCTURAL_FIXTURE',
    reason: 'The Golden Curriculum proves engine structure and runtime behavior; it is not production educational content.'
  }
};

fs.writeFileSync(path.join(exampleDir, 'coverage.json'), `${JSON.stringify(generateCoverage(source), null, 2)}\n`);
fs.writeFileSync(path.join(exampleDir, 'curriculum.json'), `${JSON.stringify(runtime, null, 2)}\n`);
fs.writeFileSync(path.join(exampleDir, 'validation-report.json'), `${JSON.stringify(validationReport, null, 2)}\n`);

const publishedDir = path.join(root, 'src', 'curriculum-v2', 'catalog', 'published');
fs.mkdirSync(publishedDir, { recursive: true });
fs.writeFileSync(
  path.join(publishedDir, 'goldenCurriculum.js'),
  `// Generated by npm run curriculum:v2:golden. Do not edit manually.\nexport default ${JSON.stringify(runtime, null, 2)};\n`
);
console.log(`Built Golden Curriculum ${source.curriculumId} revision ${source.revision}.`);
