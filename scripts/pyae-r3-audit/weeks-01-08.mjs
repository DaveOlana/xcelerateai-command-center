const inspectedAt = '2026-09-09';

const access = Object.freeze({
  status: 'verified',
  free: true,
  loginRequired: false,
  sectionVerified: true,
});

const candidate = (title, url, provider, disposition, reason) => ({
  title,
  url,
  provider,
  disposition,
  reason,
});

const judgment = (name, {
  beginnerClarity,
  competencyFit,
  correctness = `${name} was checked against the current destination and contains no material factual defect in the assigned scope.`,
  currency = `${name} was current and reachable when inspected on ${inspectedAt}.`,
  pacing,
  practiceQuality,
  redundancy,
}) => ({
  beginnerClarity,
  competencyFit,
  correctness,
  currency,
  pacing,
  practiceQuality,
  redundancy,
});

function makeResourcePlan({
  id,
  weekId,
  decision = 'retained',
  title,
  url,
  provider,
  format,
  estimatedMinutes,
  location,
  competencyIds,
  role,
  learningRole,
  purpose,
  whySelected,
  selectionPurposes,
  formatRationale,
  alternativeNotes,
  candidateComparisons,
  judgment: resourceJudgment,
  rationale,
}) {
  return {
    weekId,
    decision,
    resourcePatch: {
      id,
      title,
      url,
      provider,
      format,
      cost: 'free',
      estimatedMinutes,
      location: { note: location },
      competencyIds,
      whySelected,
      accessStatus: 'verified',
      checkedAt: inspectedAt,
      selectionRole: role,
      formatRationale,
      purpose: selectionPurposes,
      evaluation: {
        competencyFit: resourceJudgment.competencyFit,
        clarity: resourceJudgment.beginnerClarity,
        correctnessAndCurrency: `${resourceJudgment.correctness} ${resourceJudgment.currency}`,
        accessibility: 'The assigned destination is free, public, and requires no learner account.',
      },
      accessNotes: `The destination and assigned section were opened on ${inspectedAt}; no payment or account is required.`,
      alternativeNotes,
    },
    assignment: {
      resourceId: id,
      role,
      learningRole,
      competencyIds,
      purpose,
    },
    actualContentInspected: true,
    inspectedAt,
    access: { ...access },
    candidateComparisons,
    judgment: resourceJudgment,
    rationale,
  };
}

function makeAddedResourcePlan(spec) {
  const plan = makeResourcePlan({ ...spec, decision: 'added' });
  return {
    ...plan,
    resource: plan.resourcePatch,
  };
}

