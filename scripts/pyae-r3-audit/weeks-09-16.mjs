function makeQuestionWeek({
  weekId,
  classification,
  supportingResourceIds,
  priorCompetencyIds,
  patches,
}) {
  const questionIds = Array.from(
    { length: 10 },
    (_, index) => `PYAE-Q-${weekId.slice(-3)}-${String(index + 1).padStart(2, '0')}`,
  );
  const byClass = Object.fromEntries(
    ['A', 'B', 'C', 'D'].map((className) => [
      className,
      questionIds.filter((_, index) => classification[index] === className),
    ]),
  );
  const evidenceBasisByClass = {
    A: 'Each listed answer is explicitly taught or demonstrated by the named Core resource assignment in this week.',
    B: 'Each listed answer relies on a competency explicitly taught and practiced before this week.',
    C: 'Each listed answer is derivable by applying this week\'s taught principles to a small scenario; no new API fact is required.',
    D: 'No final question retains an untaught dependency.',
  };

  return {
    classification,
    finalClassifications: classification,
    supportingResourceIds,
    evidenceBasis: Object.entries(evidenceBasisByClass).map(
      ([className, basis]) => `${className}: ${basis}`,
    ),
    evidenceBasisByClass,
    supportByClass: {
      A: {
        questionIds: byClass.A,
        resourceIds: [...new Set(byClass.A.flatMap((id) => supportingResourceIds[id] ?? []))],
        basis: evidenceBasisByClass.A,
      },
      B: {
        questionIds: byClass.B,
        competencyIds: priorCompetencyIds,
        basis: evidenceBasisByClass.B,
      },
      C: {
        questionIds: byClass.C,
        resourceIds: [...new Set(byClass.C.flatMap((id) => supportingResourceIds[id] ?? []))],
        basis: evidenceBasisByClass.C,
      },
      D: { questionIds: byClass.D, basis: evidenceBasisByClass.D },
    },
    patches,
  };
}

