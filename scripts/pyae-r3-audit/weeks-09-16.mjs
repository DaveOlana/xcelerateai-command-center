const checkedAt = '2026-09-09';

const judgment = (
  beginnerClarity,
  competencyFit,
  factualCorrectness,
  currency,
  stageAppropriateness,
  guidedPractice,
  accessibility,
) => ({
  beginnerClarity,
  competencyFit,
  factualCorrectness,
  currency,
  stageAppropriateness,
  guidedPractice,
  accessibility,
});

const candidate = (title, url, decision, evidence) => ({ title, url, decision, evidence });

function makeResourcePlan({
  weekId,
  decision,
  title,
  url,
  provider,
  format,
  estimatedMinutes,
  location,
  competencyIds,
  role,
  learningRole,
  purposes,
  assignmentPurpose,
  whySelected,
  formatRationale,
  alternativeNotes,
  candidateComparisons,
  judgment: resourceJudgment,
  rationale,
}) {
  const resourcePatch = {
    title,
    url,
    provider,
    format,
    cost: 'free',
    estimatedMinutes,
    location: { note: location },
    competencyIds,
    whySelected,
    accessStatus: 'verified',
    checkedAt,
    selectionRole: role,
    learningRole,
    formatRationale,
    purpose: purposes,
    evaluation: {
      competencyFit: resourceJudgment.competencyFit,
      clarity: resourceJudgment.beginnerClarity,
      correctnessAndCurrency:
        `${resourceJudgment.factualCorrectness} ${resourceJudgment.currency}`,
      accessibility: resourceJudgment.accessibility,
    },
    accessNotes:
      'The destination and assigned sections opened publicly on 2026-09-09; no payment or learner account is required.',
    alternativeNotes,
  };

  return {
    weekId,
    decision,
    resourcePatch,
    assignment: {
      role,
      learningRole,
      competencyIds,
      purpose: assignmentPurpose,
    },
    candidateComparisons,
    judgment: resourceJudgment,
    rationale,
  };
}

function makeAddedResourcePlan(id, spec) {
  const plan = makeResourcePlan(spec);
  return {
    weekId: plan.weekId,
    resource: { id, ...plan.resourcePatch },
    assignment: plan.assignment,
    candidateComparisons: plan.candidateComparisons,
    judgment: plan.judgment,
    rationale: plan.rationale,
  };
}

