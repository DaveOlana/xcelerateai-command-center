const OPTION_IDS = Object.freeze(['a', 'b', 'c', 'd']);

// Authored positions are deliberately irregular and balanced within every
// week. The learner runtime reshuffles the options again for each attempt.
const ANSWER_POSITIONS = Object.freeze({
  1: [2, 0, 3, 1, 3, 2, 0, 1, 2, 0],
  2: [1, 3, 0, 2, 0, 2, 1, 3, 1, 0],
  3: [3, 1, 2, 0, 2, 0, 3, 1, 0, 2],
  4: [0, 2, 1, 3, 1, 3, 2, 0, 3, 1],
  5: [2, 1, 3, 0, 3, 0, 2, 1, 0, 3],
  6: [1, 0, 2, 3, 0, 3, 1, 2, 3, 0],
  7: [3, 2, 0, 1, 2, 1, 3, 0, 1, 2],
  8: [0, 3, 1, 2, 1, 2, 0, 3, 2, 1],
});

const makeQuestion = (weekNumber, questionNumber, record) => {
  const targetCorrect = ANSWER_POSITIONS[weekNumber][questionNumber - 1];
  const orderedOptions = [...record.options];
  [orderedOptions[record.correct], orderedOptions[targetCorrect]] = [orderedOptions[targetCorrect], orderedOptions[record.correct]];

  return Object.freeze({
    id: `WEBD-R2-Q-W${String(weekNumber).padStart(2, '0')}-${String(questionNumber).padStart(2, '0')}`,
    weekId: `WEBD-R2-W${String(weekNumber).padStart(2, '0')}`,
    competencyIds: Object.freeze([...record.competencyIds]),
    target: record.target,
    classification: record.classification ?? 'A',
    supportingResourceIds: Object.freeze([...record.supportingResourceIds]),
    assessmentType: record.assessmentType,
    prompt: record.prompt,
    options: Object.freeze(OPTION_IDS.map((id, index) => Object.freeze({ id, label: orderedOptions[index] }))),
    correctOptionId: OPTION_IDS[targetCorrect],
    explanation: record.explanation,
  });
};

const week = (weekNumber, records) => Object.freeze(
  records.map((record, index) => makeQuestion(weekNumber, index + 1, record)),
);

